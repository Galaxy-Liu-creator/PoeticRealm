import assert from 'node:assert/strict';
import {readAsset} from './asset-contract.mjs';
import {parseGLB} from './optimize-assets.mjs';
import {decodeExactViews} from './meshopt-exact.mjs';
const asset=await readAsset(process.argv[2]);
const {gltf,binary}=parseGLB(asset.bytes);
const index=gltf.bufferViews.findIndex(v=>v.extensions?.EXT_meshopt_compression);
assert(index>=0,'A compressed real asset is required');
const broken=()=>structuredClone(gltf);
let fixture=broken();delete fixture.extensionsRequired;
await assert.rejects(decodeExactViews(fixture,binary),/used\/required/);
fixture=broken();fixture.bufferViews[index].extensions.EXT_meshopt_compression.count++;
await assert.rejects(decodeExactViews(fixture,binary),/decoded size/);
fixture=broken();fixture.bufferViews[index].extensions.EXT_meshopt_compression.filter='EXPONENTIAL';
await assert.rejects(decodeExactViews(fixture,binary),/without filters/);
fixture=broken();fixture.bufferViews[index].extensions.EXT_meshopt_compression.byteOffset=binary.length;
await assert.rejects(decodeExactViews(fixture,binary),/compressed range/);
fixture=broken();fixture.buffers[1].byteLength=1;
await assert.rejects(decodeExactViews(fixture,binary),/placeholder/);
fixture=broken();fixture.bufferViews[index].extensions.EXT_meshopt_compression.mode='TRIANGLES';
await assert.rejects(decodeExactViews(fixture,binary),/exact meshopt/);
const corrupt=Buffer.from(binary),ext=gltf.bufferViews[index].extensions.EXT_meshopt_compression;
corrupt[ext.byteOffset]=0;
await assert.rejects(decodeExactViews(gltf,corrupt));
console.log('PASS: real r186 decode and seven meshopt corruption/precision fixtures');
